#!/usr/bin/env python3
"""One-time split of the monolithic index.html into data files plus a template.

After this runs, index.html is generated by build.py from:
    tools/template.html      (markup + CSS + engine JS, with __PLACEHOLDER__ slots)
    data/cases.json          (PBL cases + quiz questions)
    data/videos.json         (video library)
    data/meta.json           (titles, categories, tracks, explanation sets)
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "index.html")

text = open(SRC, encoding="utf-8").read()

SLOTS = {
    "CASES": "const casesData = ",
    "VIDEOS": "const VIDEO_DATA = ",
    "REGION_TITLES": "const REGION_TITLES = ",
    "CATEGORY_TITLES": "const CATEGORY_TITLES = ",
    "CAT_META": "const CAT_META = ",
}

found = {}
for name, prefix in SLOTS.items():
    i = text.index(prefix)
    start = i + len(prefix)
    end = text.index("\n", start)
    raw = text[start:end].strip()
    if raw.endswith(";"):
        raw = raw[:-1]
    found[name] = json.loads(raw)
    text = text[:start] + "__" + name + "__" + text[end:]

os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
os.makedirs(os.path.join(ROOT, "tools"), exist_ok=True)

for name, payload in (
    ("cases", found["CASES"]),
    ("videos", found["VIDEOS"]),
    ("meta", {k: found[k] for k in ("REGION_TITLES", "CATEGORY_TITLES", "CAT_META")}),
):
    path = os.path.join(ROOT, "data", name + ".json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=1)
    print("wrote", path)

with open(os.path.join(ROOT, "tools", "template.html"), "w", encoding="utf-8") as fh:
    fh.write(text)
print("wrote", os.path.join(ROOT, "tools", "template.html"))

# sanity: every slot present exactly once
for name in SLOTS:
    token = "__" + name + "__"
    assert text.count(token) == 1, (token, text.count(token))
print("slots ok:", ", ".join(sorted(SLOTS)))
